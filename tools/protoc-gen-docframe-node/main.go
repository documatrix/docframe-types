// protoc-gen-docframe-node is a protoc plugin which generates ToNode()
// conversion methods for every message type that is a member of the
// Node.object oneof. It is invoked through buf (see buf.gen.yaml).
package main

import (
	"fmt"

	"google.golang.org/protobuf/compiler/protogen"
	"google.golang.org/protobuf/types/pluginpb"
)

const (
	nodeMessageName = "Node"
	nodeOneofName   = "object"
)

func main() {
	protogen.Options{}.Run(func(gen *protogen.Plugin) error {
		gen.SupportedFeatures = uint64(pluginpb.CodeGeneratorResponse_FEATURE_PROTO3_OPTIONAL)

		nodeFile, node := findNode(gen)
		if node == nil {
			// Partial generation (buf generate --path ...) without node.proto: nothing to emit.
			return nil
		}

		var oneof *protogen.Oneof
		for _, o := range node.Oneofs {
			if o.Desc.Name() == nodeOneofName {
				oneof = o
				break
			}
		}
		if oneof == nil {
			return fmt.Errorf("oneof %q not found in message %q", nodeOneofName, nodeMessageName)
		}

		g := gen.NewGeneratedFile(nodeFile.GeneratedFilenamePrefix+".tonode.pb.go", nodeFile.GoImportPath)
		g.P("// Code generated by protoc-gen-docframe-node. DO NOT EDIT.")
		g.P("// source: ", nodeFile.Desc.Path())
		g.P()
		g.P("package ", nodeFile.GoPackageName)
		g.P()

		for _, field := range oneof.Fields {
			if field.Message == nil {
				return fmt.Errorf("oneof member %s.%s is not a message", nodeMessageName, field.Desc.Name())
			}

			g.P("// ToNode wraps the ", field.Message.GoIdent.GoName, " in a Node and attaches the given children.")
			g.P("func (x *", field.Message.GoIdent, ") ToNode(children ...Message) *", node.GoIdent, " {")
			g.P("	nodeChildren := make([]*", node.GoIdent, ", len(children))")
			g.P("	for i, c := range children {")
			g.P("		nodeChildren[i] = c.ToNode()")
			g.P("	}")
			g.P()
			g.P("	return &", node.GoIdent, "{")
			g.P("		Object: &", field.GoIdent, "{", field.GoName, ": x},")
			g.P("		Children: nodeChildren,")
			g.P("	}")
			g.P("}")
			g.P()
		}

		return nil
	})
}

func findNode(gen *protogen.Plugin) (*protogen.File, *protogen.Message) {
	for _, f := range gen.Files {
		if !f.Generate {
			continue
		}
		for _, m := range f.Messages {
			if m.Desc.Name() == nodeMessageName {
				return f, m
			}
		}
	}
	return nil, nil
}
